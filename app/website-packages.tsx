import { ArrowUpRight, Check } from 'lucide-react';
import { money } from './site-data';
import { websiteOffers } from './website-offers';
import './website-offers.css';

const customOffer = {
  slug: 'nine-x',
  name: 'Nine X',
  price: null,
  label: 'INDIVIDUELL GEPLANT',
  goal: 'Dein Vorhaben hat seinen eigenen Umfang.',
  includes: [
    'Funktionen nach deinem Bedarf',
    'Web-Apps, Portale & Schnittstellen',
    'Persönliches Angebot nach Abstimmung',
  ],
  note: 'Leistungen und Zeitplan legen wir gemeinsam fest.',
};

export function WebsitePackages({
  detailed = false,
  headingLevel = 3,
}: {
  detailed?: boolean;
  headingLevel?: 2 | 3;
}) {
  const OfferHeading = headingLevel === 2 ? 'h2' : 'h3';
  return (
    <div className="website-offers">
      <div className="website-offer-grid">
        {[...websiteOffers, customOffer].map((offer) => (
          <article
            className={
              'website-offer' +
              (offer.slug === 'nine-growth' ? ' website-offer-growth' : '')
            }
            key={offer.slug}
            id={offer.slug}
          >
            <span className="website-offer-label">{offer.label}</span>
            <OfferHeading>{offer.name}</OfferHeading>
            <p>{offer.goal}</p>
            <div className="website-offer-price">
              <strong>
                {offer.price === null ? 'Auf Anfrage' : money(offer.price)}
              </strong>
              <span>
                {offer.price === null
                  ? 'Individuelles Angebot'
                  : 'einmalig · netto'}
              </span>
            </div>
            <ul>
              {offer.includes.map((item) => (
                <li key={item}>
                  <Check size={16} aria-hidden="true" />
                  {item}
                </li>
              ))}
            </ul>
            <a
              className={
                'c-button ' +
                (offer.slug === 'nine-growth'
                  ? 'c-button-light'
                  : 'c-button-blue')
              }
              href={
                '/website-erstellen-lassen?paket=' +
                (offer.slug === 'nine-x' ? 'unsicher' : offer.slug) +
                '#website-check'
              }
            >
              {offer.slug === 'nine-x'
                ? 'Persönlich besprechen'
                : 'Unverbindlich anfragen'}{' '}
              <ArrowUpRight size={18} aria-hidden="true" />
            </a>
            {detailed && <p className="website-offer-note">{offer.note}</p>}
            {detailed &&
              ['nine-launch', 'nine-growth'].includes(offer.slug) && (
                <a
                  className="website-order-link"
                  href={'/checkout/' + offer.slug}
                >
                  Bestellentwurf vorbereiten <ArrowUpRight size={15} />
                </a>
              )}
          </article>
        ))}
      </div>
      <div className="website-offer-terms">
        <p>
          Festpreise gelten für den genannten Umfang. Hosting, Domain,
          Fremdlizenzen und zusätzliche Inhalte kommen separat dazu. Bei Growth
          sind Werbebudget und laufende Ads-Betreuung nicht enthalten.
        </p>
        {detailed ? (
          <p>
            Ein Seitenlayout ist ein Seitentyp, zum Beispiel Startseite oder
            Leistungsseite. Shop, Login und besondere Schnittstellen stimmen wir
            gesondert ab. Nine Start nutzt vorhandene Texte und Bilder; die
            spätere Inhaltspflege wird separat vereinbart.
          </p>
        ) : (
          <a className="c-inline-link" href="/pakete">
            Alle Leistungen im Detail <ArrowUpRight size={17} />
          </a>
        )}
      </div>
    </div>
  );
}
